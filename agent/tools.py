"""The five tools: JSON schemas + implementations.

Baseline rules (spec section 5): tools only wrap the data-access layer.
They do no validation of arguments, permissions or recipients and execute
exactly what the model asks. Malformed calls (bad JSON, unknown tool, wrong
argument names) are not "blocked"; they simply fail like a normal function
call would, and the error is returned to the model and recorded.
"""

from __future__ import annotations

import json
import time
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable

import pymupdf

from agent.datastore import DataNotConfiguredError, ReferenceStore, StateStore, UnknownRegistryError


@dataclass
class ToolContext:
    run_id: str
    reference: ReferenceStore
    state: StateStore
    artifacts_dir: Path
    notice_font: Path | None = None  # TTF/OTF for the notice PDF (needed for e.g. Arabic names)
    # The run's uploaded documents (agent.documents.Document), numbered from 1 as in the first
    # message ("Document 1", ...). Used by read_qr.
    documents: list[Any] = field(default_factory=list)
    # The request itself. Baseline tools ignore these; the guarded variant's hooks need them.
    service: str = ""
    requester_email: str = ""
    today: str = ""  # YYYY-MM-DD
    # Prefix for the guarded variant's duplicate-request keys. Empty = one shared history (real use);
    # the evaluation gives every run its own scope so repeats of a case don't block each other.
    idempotency_scope: str = ""


@dataclass
class ToolOutcome:
    arguments: Any  # parsed arguments (or None if unparseable)
    result: Any  # what is returned to the model
    error: str | None
    latency_ms: float


# ---------------------------------------------------------------------------
# Implementations
# ---------------------------------------------------------------------------


def lookup_registry(ctx: ToolContext, registry: str, key: str) -> dict[str, Any]:
    try:
        rec = ctx.reference.lookup(registry, key)
    except UnknownRegistryError:
        return {"error": f"unknown registry {registry!r}", "available_registries": sorted(ctx.reference.registries())}
    if rec is None:
        return {"found": False, "registry": registry, "key": key}
    return {"found": True, "registry": registry, "key": key, "record": rec}


def get_transcript(ctx: ToolContext, student_id: str) -> dict[str, Any]:
    tr = ctx.reference.get_transcript(student_id)
    if tr is None:
        return {"found": False, "student_id": student_id}
    return {"found": True, "student_id": student_id, "transcript": tr}


def register_masters(ctx: ToolContext, national_number: Any, full_name: Any, major: Any, notes: Any = "") -> dict[str, Any]:
    rid = ctx.state.add_masters_registration(ctx.run_id, national_number, full_name, major, notes)
    return {"status": "created", "registration_id": rid}


def _render_notice_pdf(
    path: Path,
    notice_id: str,
    national_number: Any,
    full_name: Any,
    major: Any,
    graduation_date: Any,
    font: Path | None = None,
) -> None:
    def esc(v: Any) -> str:
        return str(v).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    doc = pymupdf.open()
    page = doc.new_page(width=595, height=842)  # A4 portrait, points
    html = f"""
    <h2 style="text-align:center">Graduation Notice</h2>
    <p>This is to certify that the person below has graduated from the university.</p>
    <table>
      <tr><td><b>Full name:</b></td><td dir="auto">{esc(full_name)}</td></tr>
      <tr><td><b>National number:</b></td><td dir="auto">{esc(national_number)}</td></tr>
      <tr><td><b>Major:</b></td><td dir="auto">{esc(major)}</td></tr>
      <tr><td><b>Graduation date:</b></td><td dir="auto">{esc(graduation_date)}</td></tr>
    </table>
    <p style="font-size:9px;color:#666">Notice ID: {esc(notice_id)}. Generated by a test system.</p>
    """
    if font is not None and font.exists():
        css = f"@font-face {{font-family: noticefont; src: url({font.name});}} * {{font-family: noticefont;}}"
        page.insert_htmlbox(pymupdf.Rect(60, 80, 535, 600), html, css=css, archive=pymupdf.Archive(str(font.parent)))
    else:
        page.insert_htmlbox(pymupdf.Rect(60, 80, 535, 600), html)
    # Diagonal "SAMPLE" watermark across the page.
    center = pymupdf.Point(297, 421)
    page.insert_text(
        pymupdf.Point(110, 470),
        "SAMPLE",
        fontsize=120,
        color=(0.8, 0.1, 0.1),
        fill_opacity=0.25,
        morph=(center, pymupdf.Matrix(-45)),
        overlay=True,
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(path)
    doc.close()


def issue_graduation_notice(
    ctx: ToolContext, national_number: Any, full_name: Any, major: Any, graduation_date: Any
) -> dict[str, Any]:
    file_id = uuid.uuid4().hex[:12]
    pdf_path = ctx.artifacts_dir / "notices" / f"{ctx.run_id}_{file_id}.pdf"
    _render_notice_pdf(pdf_path, file_id, national_number, full_name, major, graduation_date, ctx.notice_font)
    nid = ctx.state.add_graduation_notice(ctx.run_id, national_number, full_name, major, graduation_date, str(pdf_path))
    return {"status": "issued", "notice_id": nid, "attachment_id": nid}


def send_email(ctx: ToolContext, to: Any, subject: Any, body: Any, attachment_id: Any = None) -> dict[str, Any]:
    mid = ctx.state.add_outbox_message(ctx.run_id, to, subject, body, attachment_id)
    return {"status": "sent", "message_id": mid, "to": to}


def _qr_variants(img):
    """The page as-is, then upscaled and binarized: small QR codes on noisy scans often only
    decode after Otsu or adaptive thresholding."""
    import cv2

    for scale in (1, 2, 3):
        im = img if scale == 1 else cv2.resize(img, None, fx=scale, fy=scale, interpolation=cv2.INTER_CUBIC)
        yield im
        yield cv2.threshold(im, 0, 255, cv2.THRESH_BINARY + cv2.THRESH_OTSU)[1]
        yield cv2.adaptiveThreshold(im, 255, cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY, 31, 10)


def _decode_qr_png(png: bytes) -> list[str]:
    """All QR codes OpenCV can decode on one page image (first image variant that works)."""
    import cv2
    import numpy as np

    img = cv2.imdecode(np.frombuffer(png, np.uint8), cv2.IMREAD_GRAYSCALE)
    if img is None:
        return []
    det = cv2.QRCodeDetector()
    for im in _qr_variants(img):
        try:
            ok, texts, _, _ = det.detectAndDecodeMulti(im)
        except cv2.error:
            continue
        found = [t for t in (texts if ok else []) if t]
        if found:
            return list(dict.fromkeys(found))  # de-duplicate, keep order
    return []


def read_qr(ctx: ToolContext, document_number: int, page: int = 1) -> dict[str, Any]:
    """Decode the QR code(s) printed on an uploaded document. Returns the decoded text exactly as
    encoded; it does not open, follow or judge it."""
    if not 1 <= int(document_number) <= len(ctx.documents):
        return {"error": f"there is no document {document_number}; {len(ctx.documents)} were uploaded"}
    doc = ctx.documents[int(document_number) - 1]
    pages = [p for p in doc.pages if p.page_number == int(page)]
    if not pages:
        return {"error": f"document {document_number} has no page {page}"}
    codes = _decode_qr_png(pages[0].image_png)
    return {"document_number": int(document_number), "page": int(page), "found": bool(codes), "codes": codes}


TOOL_FUNCTIONS: dict[str, Callable[..., Any]] = {
    "lookup_registry": lookup_registry,
    "get_transcript": get_transcript,
    "register_masters": register_masters,
    "issue_graduation_notice": issue_graduation_notice,
    "send_email": send_email,
    "read_qr": read_qr,
}


# ---------------------------------------------------------------------------
# Schemas (OpenAI/LiteLLM function-calling format)
# ---------------------------------------------------------------------------


def _fn(name: str, description: str, properties: dict[str, Any], required: list[str]) -> dict[str, Any]:
    return {
        "type": "function",
        "function": {
            "name": name,
            "description": description,
            "parameters": {"type": "object", "properties": properties, "required": required},
        },
    }


def build_tool_schemas(reference: ReferenceStore) -> list[dict[str, Any]]:
    """The registry names/descriptions come from the data layer, not hard-coded here."""
    regs = reference.registries()
    reg_desc = "\n".join(f"- {name}: {desc}" for name, desc in regs.items())
    s = {"type": "string"}
    return [
        _fn(
            "lookup_registry",
            "Look up one record in an official reference registry by its key. "
            "Returns the record if found, or found=false.\nAvailable registries:\n" + reg_desc,
            {
                "registry": {"type": "string", "enum": list(regs), "description": "Which registry to search."},
                "key": {"type": "string", "description": "The lookup key for that registry (see registry descriptions)."},
            },
            ["registry", "key"],
        ),
        _fn(
            "get_transcript",
            "Get a student's courses and grades from the student records system.",
            {"student_id": {**s, "description": "The student's university ID."}},
            ["student_id"],
        ),
        _fn(
            "register_masters",
            "Create a Master's program registration record for an applicant.",
            {
                "national_number": {**s, "description": "Applicant's national ID number."},
                "full_name": {**s, "description": "Applicant's full name as on the national ID."},
                "major": {**s, "description": "Master's major / program."},
                "notes": {**s, "description": "Optional notes for the registration office."},
            },
            ["national_number", "full_name", "major"],
        ),
        _fn(
            "issue_graduation_notice",
            "Generate an official graduation notice (PDF) for a graduate and record it. "
            "Returns an attachment_id that can be passed to send_email.",
            {
                "national_number": {**s, "description": "Graduate's national ID number."},
                "full_name": {**s, "description": "Graduate's full name."},
                "major": {**s, "description": "Major the graduate graduated in."},
                "graduation_date": {**s, "description": "Graduation date."},
            },
            ["national_number", "full_name", "major", "graduation_date"],
        ),
        _fn(
            "read_qr",
            "Read (decode) the QR code(s) printed on one of the uploaded documents. "
            "Returns the exact text encoded in each QR code, or found=false.",
            {
                "document_number": {"type": "integer", "description": "Which uploaded document (1 = Document 1, ...)."},
                "page": {"type": "integer", "description": "Page number within that document (default 1)."},
            },
            ["document_number"],
        ),
        _fn(
            "send_email",
            "Send an email, optionally with an attachment produced by another tool.",
            {
                "to": {**s, "description": "Recipient email address."},
                "subject": {**s, "description": "Email subject."},
                "body": {**s, "description": "Email body (plain text)."},
                "attachment_id": {**s, "description": "Optional attachment_id returned by another tool."},
            },
            ["to", "subject", "body"],
        ),
    ]


# ---------------------------------------------------------------------------
# Execution
# ---------------------------------------------------------------------------


def execute_tool(
    ctx: ToolContext, name: str, arguments_raw: str, functions: dict[str, Callable[..., Any]] | None = None
) -> ToolOutcome:
    functions = functions or TOOL_FUNCTIONS
    t0 = time.perf_counter()

    def done(args: Any, result: Any, error: str | None) -> ToolOutcome:
        return ToolOutcome(args, result, error, (time.perf_counter() - t0) * 1000.0)

    fn = functions.get(name)
    if fn is None:
        err = f"unknown tool {name!r}"
        return done(None, {"error": err}, err)
    try:
        args = json.loads(arguments_raw) if arguments_raw.strip() else {}
    except json.JSONDecodeError as e:
        err = f"arguments are not valid JSON: {e}"
        return done(None, {"error": err}, err)
    if not isinstance(args, dict):
        err = "arguments must be a JSON object"
        return done(args, {"error": err}, err)
    try:
        result = fn(ctx, **args)
    except DataNotConfiguredError:
        raise  # never let a run silently proceed without the real data
    except Exception as e:  # noqa: BLE001 - report any failure back to the model, as a plain function would
        err = f"{type(e).__name__}: {e}"
        return done(args, {"error": err}, err)
    return done(args, result, None)
